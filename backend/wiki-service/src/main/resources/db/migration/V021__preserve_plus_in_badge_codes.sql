CREATE TEMP TABLE badge_renames ON COMMIT DROP AS
SELECT b.id,b.code AS old_code,m.new_code,'rename-'||gen_random_uuid() AS temporary_code
FROM hero.skin_badge b JOIN hero.skin_badge_code_alias a ON a.badge_id=b.id
JOIN badge_code_corrections m ON m.legacy_code=a.legacy_code WHERE b.code<>m.new_code;
ALTER TABLE hero.hero_skin_snapshot DISABLE TRIGGER trg_hero_skin_snapshot_immutable;
UPDATE hero.hero_skin_snapshot s SET rarity_code=m.temporary_code FROM badge_renames m WHERE s.rarity_code=m.old_code;
UPDATE hero.skin_badge b SET code=m.temporary_code FROM badge_renames m WHERE b.id=m.id;
UPDATE hero.skin_badge b SET code=m.new_code FROM badge_renames m WHERE b.id=m.id;
UPDATE hero.hero_skin_snapshot s SET rarity_code=m.new_code FROM badge_renames m WHERE s.rarity_code=m.temporary_code;
ALTER TABLE hero.hero_skin_snapshot ENABLE TRIGGER trg_hero_skin_snapshot_immutable;
UPDATE hero.image_file_alias f SET file_name=m.new_code||substring(f.file_name from '\.[^.]+$')
FROM media.media_provenance p,hero.skin_badge_code_alias a,badge_code_corrections m
WHERE f.asset_id=p.asset_id AND a.legacy_code=m.legacy_code
AND replace(p.note,'/__resources/','') ~ ('/grade/'||a.legacy_code||'\.[^.]+$');
UPDATE media.media_upload_session u SET file_name=f.file_name FROM hero.image_file_alias f WHERE u.asset_id=f.asset_id;
