/** Applies `translate` to the words of a label and keeps the formatting tags around them. */
function withinTags(value: string, translate: (text: string) => string | undefined) {
  const match = /^(\s*(?:<[^<>]+>\s*)*)([^<>]*?)(\s*(?:<\/[^<>]+>\s*)*)$/.exec(value)
  if (!match) return value
  const translated = translate(match[2].trim())
  return translated === undefined ? value : `${match[1]}${translated}${match[3]}`
}

const english = (locale: string) => locale.startsWith("en")

/** A row label of the level table, such as the base damage row. */
export function localizedRankLabel(label: string, locale: string) {
  return english(locale) ? withinTags(label, (text) => RANK_LABELS[text]) : label
}

/** The cooldown or cost line of a skill, such as an 8-second cooldown or a 50 Mana cost. */
export function localizedSkillCost(display: string, locale: string) {
  if (!english(locale)) return display
  return withinTags(display, (text) => {
    for (const [pattern, replacement] of COST_LABELS) if (pattern.test(text)) return text.replace(pattern, replacement)
    return undefined
  })
}

/** The name of a skill's form, such as its enhanced form. */
export function localizedFormName(name: string, locale: string) {
  return (english(locale) && FORM_NAMES[name.trim()]) || name
}

/** The label of a state that only changes the skill's picture, such as its recast state. */
export function localizedStateName(name: string, locale: string) {
  return (english(locale) && STATE_NAMES[name.trim()]) || name
}
