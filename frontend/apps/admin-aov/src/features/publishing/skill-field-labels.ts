/** Scoped API keys share their final field's label; unknown codes never become reader-facing headings. */
export function skillFieldLabel(key: string): string {
  const field = key.split(".").at(-1) ?? key
  if (Object.hasOwn(SKILL_FIELD_LABELS, field)) return SKILL_FIELD_LABELS[field]
  return /^[A-Za-z_][A-Za-z0-9_.-]*$/.test(key) ? "Thông số khác" : key
}
